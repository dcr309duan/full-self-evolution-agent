def get_core_dir() -> Path:
    """Get the path to the core/ directory."""
    # Assume this file is in core/
    return Path(__file__).parent.resolve()


def scan_py_files(core_dir: Path) -> List[Path]:
    """Scan core/ directory for all .py files (excluding __init__.py)."""
    py_files = []
    for f in core_dir.glob('*.py'):
        if f.name != '__init__.py' and f.name != '__pycache__':
            py_files.append(f)
    return py_files


def extract_imports(filepath: Path) -> Set[str]:
    """Extract all module-level imports from a Python file using AST."""
    imports = set()
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            tree = ast.parse(f.read(), filename=str(filepath))
        
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    # Get the top-level module name
                    top_level = alias.name.split('.')[0]
                    imports.add(top_level)
            elif isinstance(node, ast.ImportFrom):
                if node.module:
                    top_level = node.module.split('.')[0]
                    imports.add(top_level)
    except (SyntaxError, UnicodeDecodeError) as e:
        print(f"Warning: Could not parse {filepath}: {e}")
    
    return imports


def build_dependency_graph(py_files: List[Path]) -> Dict[str, Set[str]]:
    """Build a dependency graph mapping module names to their dependencies."""
    graph = {}
    for f in py_files:
        module_name = f.stem
        imports = extract_imports(f)
        # Filter to only include core modules and known dependencies
        core_modules = {imp for imp in imports if imp in KNOWN_DEPENDENCIES or 
                       any(f.parent.name == 'core' for f in py_files if f.stem == imp)}
        graph[module_name] = core_modules
    return graph


def topological_sort(graph: Dict[str, Set[str]]) -> List[str]:
    """Perform topological sort on the dependency graph."""
    # Build reverse dependency map
    reverse_deps = {node: set() for node in graph}
    for node, deps in graph.items():
        for dep in deps:
            if dep in reverse_deps:
                reverse_deps[dep].add(node)
    
    # Kahn's algorithm
    in_degree = {node: len(deps) for node, deps in graph.items()}
    queue = [node for node, degree in in_degree.items() if degree == 0]
    sorted_nodes = []
    
    while queue:
        node = queue.pop(0)
        sorted_nodes.append(node)
        for dependent in reverse_deps.get(node, set()):
            in_degree[dependent] -= 1
            if in_degree[dependent] == 0:
                queue.append(dependent)
    
    # If there are cycles, add remaining nodes
    remaining = set(graph.keys()) - set(sorted_nodes)
    if remaining:
        print(f"Warning: Cycle detected in dependencies: {remaining}")
        sorted_nodes.extend(remaining)
    
    return sorted_nodes


def generate_init_content(sorted_modules: List[str], graph: Dict[str, Set[str]]) -> str:
    """Generate the content for __init__.py with correct imports."""
    lines = [
        '"""Core package auto-generated by nash_bootstrap."""',
        '',
        '# Auto-generated imports in dependency order',
        '',
    ]
    
    for module in sorted_modules:
        lines.append(f'from core.{module} import *  # noqa: F401, F403')
    
    lines.extend([
        '',
        '# Explicit exports',
        '__all__ = [',
    ])
    
    for module in sorted_modules:
        lines.append(f'    "{module}",')
    
    lines.append(']')
    lines.append('')
    
    return '\n'.join(lines)


