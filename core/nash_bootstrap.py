def check_missing_dependencies(graph: Dict[str, Set[str]], core_dir: Path) -> Set[str]:
    """Check for missing dependencies and create stubs if needed."""
    existing_modules = {f.stem for f in core_dir.glob('*.py') if f.stem != '__init__'}
    all_deps = set()
    for deps in graph.values():
        all_deps.update(deps)
    
    missing = all_deps - existing_modules - {'__init__'}
    
    for dep in missing:
        if dep in KNOWN_DEPENDENCIES:
            create_stub_module(dep, core_dir)
    
    return missing


def bootstrap() -> bool:
    """Main bootstrap function. Returns True if successful."""
    try:
        core_dir = get_core_dir()
        print(f"Bootstrapping core/ directory: {core_dir}")
        
        # Scan for Python files
        py_files = scan_py_files(core_dir)
        print(f"Found {len(py_files)} Python files")
        
        # Build dependency graph
        graph = build_dependency_graph(py_files)
        print(f"Built dependency graph with {len(graph)} modules")
        
        # Check for missing dependencies
        missing = check_missing_dependencies(graph, core_dir)
        if missing:
            print(f"Created stub modules for: {', '.join(missing)}")
        
        # Re-scan after creating stubs
        py_files = scan_py_files(core_dir)
        graph = build_dependency_graph(py_files)
        
        # Topological sort
        sorted_modules = topological_sort(graph)
        print(f"Module load order: {', '.join(sorted_modules)}")
        
        # Generate __init__.py
        init_content = generate_init_content(sorted_modules, graph)
        init_path = core_dir / '__init__.py'
        
        with open(init_path, 'w', encoding='utf-8') as f:
            f.write(init_content)
        
        print(f"Generated {init_path}")
        return True
        
    except Exception as e:
        print(f"Bootstrap failed: {e}")
        return False


def main():
    """Entry point for running bootstrap directly."""
    success = bootstrap()
    sys.exit(0 if success else 1)


if __name__ == '__main__':
    main()