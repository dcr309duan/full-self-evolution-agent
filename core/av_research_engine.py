# ------------------------------------------------------------------------------
# Core engine
# ------------------------------------------------------------------------------

class AVResearchEngine:
    """
    Core research engine for audio/video topics.
    Scans the knowledge base, analyzes implementations, and generates structured reports.
    """

    def __init__(self, knowledge_base_path: str = '.'):
        self.kb_path = Path(knowledge_base_path)
        self.taxonomy = TOPIC_TAXONOMY
        self._cache: Dict[str, List[CodeSnippet]] = {}
        self._reports_dir = Path('reports/av-research')
        self._reports_dir.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------------------------------
    # Public API
    # --------------------------------------------------------------------------

    def research(self, topic: str, output_format: str = 'markdown') -> str:
        """
        Perform research on a given topic.
        
        Args:
            topic: The research topic (e.g., 'AEC', 'ANS', 'H264', 'RTP')
            output_format: 'markdown' or 'json'
        
        Returns:
            A structured research report as a string.
        """
        topic_info = self._resolve_topic(topic)
        if topic_info is None:
            return f"Error: Unknown topic '{topic}'. Available topics: {list(self.taxonomy.keys())}"

        # 1. Scan knowledge base
        snippets = self._scan_knowledge_base(topic_info)

        # 2. Analyze algorithms
        algorithms = self._analyze_algorithms(snippets, topic_info)

        # 3. Generate report
        report = self._generate_report(topic_info, snippets, algorithms)

        # 4. Write report to file
        self._write_report(report, topic_info.name)

        if output_format == 'json':
            return json.dumps(report.to_dict(), indent=2)
        else:
            return report.to_markdown()

    def research_multiple(self, topics: List[str], output_format: str = 'markdown') -> Dict[str, str]:
        """
        Perform research on multiple topics.
        
        Args:
            topics: List of research topics
            output_format: 'markdown' or 'json'
        
        Returns:
            Dictionary mapping topic names to their reports.
        """
        results = {}
        for topic in topics:
            result = self.research(topic, output_format)
            results[topic] = result
        return results

    def list_topics(self) -> List[str]:
        """Return all known topic names."""
        return list(self.taxonomy.keys())

    def get_topic_info(self, topic: str) -> Optional[Dict[str, Any]]:
        """Get detailed info about a topic."""
        t = self._resolve_topic(topic)
        if t:
            return t.to_dict()
        return None

    def add_topic(self, topic: ResearchTopic) -> None:
        """Add a custom topic to the taxonomy."""
        self.taxonomy[topic.name] = topic

    def scan_knowledge_base(self, topic: str) -> List[CodeSnippet]:
        """
        Public method to scan knowledge base for a topic.
        
        Args:
            topic: The research topic name
        
        Returns:
            List of relevant code snippets.
        """
        topic_info = self._resolve_topic(topic)
        if topic_info is None:
            return []
        return self._scan_knowledge_base(topic_info)

    # --------------------------------------------------------------------------
    # Internal helpers
    # --------------------------------------------------------------------------

    def _resolve_topic(self, name: str) -> Optional[ResearchTopic]:
        """Resolve a topic name (case-insensitive, check aliases)."""
        name_lower = name.lower().strip()
        # Direct match
        if name.upper() in self.taxonomy:
            return self.taxonomy[name.upper()]
        # Check aliases
        for key, topic in self.taxonomy.items():
            if name_lower == key.lower():
                return topic
            for alias in topic.aliases:
                if name_lower == alias.lower():
                    return topic
        return None

    def _scan_knowledge_base(self, topic: ResearchTopic) -> List[CodeSnippet]:
        """
        Scan the knowledge base directory for files matching the topic's search patterns.
        Returns a list of relevant code snippets.
        """
        if topic.name in self._cache:
            return self._cache[topic.name]

        snippets: List[CodeSnippet] = []
        patterns = topic.search_patterns
        compiled_patterns = [re.compile(p, re.IGNORECASE) for p in patterns]

        # Walk through all Python files in the knowledge base
        for file_path in self.kb_path.rglob('*.py'):
            try:
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    lines = f.readlines()
            except Exception:
                continue

            rel_path = str(file_path.relative_to(self.kb_path))
            for i, line in enumerate(lines, start=1):
                for pattern in compiled_patterns:
                    if pattern.search(line):
                        # Extract a snippet around the matched line
                        start = max(0, i - 3)
                        end = min(len(lines), i + 3)
                        snippet_content = ''.join(lines[start:end])
                        snippet = CodeSnippet(
                            file_path=rel_path,
                            line_start=start + 1,
                            line_end=end,
                            content=snippet_content.strip(),
                            relevance_score=1.0,
                            tags=[topic.name]
                        )
                        snippets.append(snippet)
                        break  # avoid duplicate matches for same line

        self._cache[topic.name] = snippets
        return snippets

    def _analyze_algorithms(
        self, snippets: List[CodeSnippet], topic: ResearchTopic
    ) -> List[AlgorithmAnalysis]:
        """
        Analyze code snippets to extract algorithm details.
        Uses AST parsing to understand function signatures and docstrings.
        """
        algorithms: Dict[str, AlgorithmAnalysis] = {}

        for snippet in snippets:
            file_path = self.kb_path / snippet.file_path
            try:
                with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                    source = f.read()
            except Exception:
                continue

            try:
                tree = ast.parse(source)
            except SyntaxError:
                continue

            # Find functions/classes that match the topic
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    func_name = node.name
                    # Check if function name or docstring matches topic keywords
                    if any(kw.lower() in func_name.lower() for kw in topic.keywords):
                        # Extract function details
                        docstring = ast.get_docstring(node) or ''
                        complexity = self._estimate_complexity(node)
                        description = docstring.split('\n')[0] if docstring else f"Function {func_name} related to {topic.name}"
                        input_output = self._extract_input_output(node)
                        
                        if func_name not in algorithms:
                            algorithms[func_name] = AlgorithmAnalysis(
                                name=func_name,
                                module_path=snippet.file_path,
                                complexity=complexity,
                                description=description,
                                input_output=input_output,
                                dependencies=self._extract_dependencies(node),
                                code_snippets=[snippet],
                                technical_principles=self._extract_principles(docstring, topic),
                                application_scenarios=self._extract_scenarios(docstring, topic)
                            )
                        else:
                            algorithms[func_name].code_snippets.append(snippet)

        return list(algorithms.values())

    def _estimate_complexity(self, node: ast.FunctionDef) -> str:
        """Estimate time complexity based on nested loops."""
        loops = 0
        for child in ast.walk(node):
            if isinstance(child, (ast.For, ast.While)):
                loops += 1
        if loops == 0:
            return 'O(1)'
        elif loops == 1:
            return 'O(n)'
        elif loops == 2:
            return 'O(n²)'
        else:
            return f'O(n^{loops})'

    def _extract_input_output(self, node: ast.FunctionDef) -> str:
        """Extract input/output description from function signature."""
        args = [arg.arg for arg in node.args.args if arg.arg != 'self']
        returns = ast.get_docstring(node) or ''
        # Try to find return description in docstring
        return_match = re.search(r'Returns?:?\s*(.*?)(?:\n|$)', returns)
        return_desc = return_match.group(1) if return_match else 'Unknown'
        return f"Inputs: {', '.join(args) if args else 'None'}; Output: {return_desc}"

    def _extract_dependencies(self, node: ast.FunctionDef) -> List[str]:
        """Extract module dependencies from function body."""
        deps = set()
        for child in ast.walk(node):
            if isinstance(child, ast.Call):
                if isinstance(child.func, ast.Attribute):
                    deps.add(child.func.attr)
                elif isinstance(child.func, ast.Name):
                    deps.add(child.func.id)
        return list(deps)[:5]  # Limit to top 5 dependencies

    def _extract_principles(self, docstring: str, topic: ResearchTopic) -> List[str]:
        """Extract technical principles from docstring."""
        principles = []
        if docstring:
            # Look for sections describing principles
            principle_match = re.search(r'Principles?:?\s*(.*?)(?:\n\n|$)', docstring, re.DOTALL)
            if principle_match:
                principles = [p.strip() for p in principle_match.group(1).split('\n') if p.strip()]
        # Add topic-specific principles if none found
        if not principles:
            principles = [
                f"Based on {topic.name} standard specifications",
                f"Implements core {topic.name} algorithms",
                f"Optimized for real-time processing"
            ]
        return principles

    def _extract_scenarios(self, docstring: str, topic: ResearchTopic) -> List[str]:
        """Extract application scenarios from docstring."""
        scenarios = []
        if docstring:
            scenario_match = re.search(r'Scenarios?:?\s*(.*?)(?:\n\n|$)', docstring, re.DOTALL)
            if scenario_match:
                scenarios = [s.strip() for s in scenario_match.group(1).split('\n') if s.strip()]
        # Add topic-specific scenarios if none found
        if not scenarios:
            scenarios = [
                f"Real-time {topic.category} processing",
                f"Integration with {topic.name} systems",
                f"Performance optimization for {topic.name}"
            ]
        return scenarios

    def _generate_report(
        self, topic: ResearchTopic, snippets: List[CodeSnippet], 
        algorithms: List[AlgorithmAnalysis]
    ) -> ResearchReport:
        """Generate a structured research report."""
        # Build summary
        summary = f"Research report for {topic.name} ({topic.category}). "
        summary += f"Found {len(snippets)} relevant code snippets and {len(algorithms)} algorithm implementations. "
        summary += f"Related topics: {', '.join(topic.related_topics)}."

        # Build technical principles
        technical_principles = []
        if algorithms:
            for algo in algorithms:
                technical_principles.extend(algo.technical_principles)
        if not technical_principles:
            technical_principles = [
                f"{topic.name} is a {topic.category} technology used in audio/video processing",
                f"Implements standard algorithms for {topic.name.lower()}",
                f"Optimized for low-latency real-time applications"
            ]

        # Build application scenarios
        application_scenarios = []
        if algorithms:
            for algo in algorithms:
                application_scenarios.extend(algo.application_scenarios)
        if not application_scenarios:
            application_scenarios = [
                f"Real-time {topic.category} processing in communication systems",
                f"Integration with multimedia frameworks",
                f"Performance-critical audio/video pipelines"
            ]

        # Build code examples
        code_examples = []
        for snippet in snippets[:3]:  # Limit to top 3 snippets
            code_examples.append(snippet.content)

        # Build references
        references = []
        for snippet in snippets:
            ref = f"File: {snippet.file_path} (lines {snippet.line_start}-{snippet.line_end})"
            if ref not in references:
                references.append(ref)

        return ResearchReport(
            topic=topic.name,
            summary=summary,
            technical_principles=technical_principles,
            algorithm_details=algorithms,
            application_scenarios=application_scenarios,
            related_topics=topic.related_topics,
            references=references,
            code_examples=code_examples,
            metadata={
                'category': topic.category,
                'keywords': topic.keywords,
                'snippet_count': len(snippets),
                'algorithm_count': len(algorithms)
            }
        )

    def _write_report(self, report: ResearchReport, topic_name: str) -> None:
        """Write the report to a markdown file in the reports directory."""
        # Create topic-specific directory
        topic_dir = self._reports_dir / topic_name.lower()
        topic_dir.mkdir(parents=True, exist_ok=True)

        # Write markdown report
        report_file = topic_dir / f"{topic_name.lower()}_report.md"
        with open(report_file, 'w', encoding='utf-8') as f:
            f.write(report.to_markdown())

        # Write JSON version for programmatic access
        json_file = topic_dir / f"{topic_name.lower()}_report.json"
        with open(json_file, 'w', encoding='utf-8') as f:
            json.dump(report.to_dict(), f, indent=2)

    def generate_index(self) -> str:
        """Generate an index of all available reports."""
        index_lines = ["# AV Research Reports Index", ""]
        for topic_name in sorted(self.taxonomy.keys()):
            topic = self.taxonomy[topic_name]
            report_path = self._reports_dir / topic_name.lower() / f"{topic_name.lower()}_report.md"
            if report_path.exists():
                index_lines.append(f"- [{topic_name} ({topic.category})]({report_path})")
            else:
                index_lines.append(f"- [{topic_name} ({topic.category})] - No report generated yet")
        return "\n".join(index_lines)

    def write_index(self) -> None:
        """Write the index file to the reports directory."""
        index_content = self.generate_index()
        index_file = self._reports_dir / "INDEX.md"
        with open(index_file, 'w', encoding='utf-8') as f:
            f.write(index_content)