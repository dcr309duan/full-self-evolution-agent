# ------------------------------------------------------------------------------
# Data structures
# ------------------------------------------------------------------------------

@dataclass
class ResearchTopic:
    """Represents a research topic with its taxonomy and search patterns."""
    name: str
    category: str          # e.g., 'codec', 'protocol', 'algorithm', 'system'
    aliases: List[str] = field(default_factory=list)
    keywords: List[str] = field(default_factory=list)
    search_patterns: List[str] = field(default_factory=list)
    related_topics: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'ResearchTopic':
        return cls(**data)


@dataclass
class CodeSnippet:
    """Represents a relevant code snippet found in the knowledge base."""
    file_path: str
    line_start: int
    line_end: int
    content: str
    language: str = 'python'
    relevance_score: float = 0.0
    tags: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class AlgorithmAnalysis:
    """Holds analysis of an algorithm implementation."""
    name: str
    module_path: str
    complexity: str          # e.g., 'O(n)', 'O(n log n)'
    description: str
    input_output: str
    dependencies: List[str] = field(default_factory=list)
    code_snippets: List[CodeSnippet] = field(default_factory=list)
    technical_principles: List[str] = field(default_factory=list)
    application_scenarios: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ResearchReport:
    """Complete research report generated by the engine."""
    topic: str
    summary: str
    technical_principles: List[str] = field(default_factory=list)
    algorithm_details: List[AlgorithmAnalysis] = field(default_factory=list)
    application_scenarios: List[str] = field(default_factory=list)
    related_topics: List[str] = field(default_factory=list)
    references: List[str] = field(default_factory=list)
    code_examples: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def to_markdown(self) -> str:
        """Render the report as a structured Markdown document."""
        lines = []
        lines.append(f"# Research Report: {self.topic}")
        lines.append("")
        lines.append("## Summary")
        lines.append(self.summary)
        lines.append("")
        if self.technical_principles:
            lines.append("## Technical Principles")
            for p in self.technical_principles:
                lines.append(f"- {p}")
            lines.append("")
        if self.algorithm_details:
            lines.append("## Algorithm Details")
            for algo in self.algorithm_details:
                lines.append(f"### {algo.name}")
                lines.append(f"**Module:** `{algo.module_path}`")
                lines.append(f"**Complexity:** {algo.complexity}")
                lines.append(f"**Description:** {algo.description}")
                lines.append(f"**Input/Output:** {algo.input_output}")
                if algo.dependencies:
                    lines.append(f"**Dependencies:** {', '.join(algo.dependencies)}")
                if algo.technical_principles:
                    lines.append("**Principles:**")
                    for pr in algo.technical_principles:
                        lines.append(f"- {pr}")
                if algo.application_scenarios:
                    lines.append("**Scenarios:**")
                    for sc in algo.application_scenarios:
                        lines.append(f"- {sc}")
                lines.append("")
        if self.application_scenarios:
            lines.append("## Application Scenarios")
            for sc in self.application_scenarios:
                lines.append(f"- {sc}")
            lines.append("")
        if self.code_examples:
            lines.append("## Code Examples")
            for ex in self.code_examples:
                lines.append("```python")
                lines.append(ex)
                lines.append("```")
                lines.append("")
        if self.related_topics:
            lines.append("## Related Topics")
            for rt in self.related_topics:
                lines.append(f"- {rt}")
            lines.append("")
        if self.references:
            lines.append("## References")
            for ref in self.references:
                lines.append(f"- {ref}")
            lines.append("")
        return "\n".join(lines)


