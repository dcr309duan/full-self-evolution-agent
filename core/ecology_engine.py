class EnvironmentalPressureGenerator:
    """Creates new benchmark types (performance, security, edge cases)."""
    
    def __init__(self):
        self.benchmark_types = ["performance", "security", "edge_case", "stress", "mutation"]
        self.generated_benchmarks = []
    
    def create_new_benchmark_type(self, benchmark_type: str = None) -> dict:
        """Create a new benchmark type with metadata."""
        if benchmark_type is None:
            benchmark_type = random.choice(self.benchmark_types)
        
        benchmark = {
            "type": benchmark_type,
            "name": f"{benchmark_type}_benchmark_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}",
            "created": datetime.datetime.now().isoformat(),
            "difficulty": random.choice(["easy", "medium", "hard"]),
            "description": f"Benchmark for testing {benchmark_type} scenarios"
        }
        
        self.generated_benchmarks.append(benchmark)
        return benchmark
    
    def generate_pressure(self) -> list:
        """Generate environmental pressure by creating multiple benchmarks."""
        pressures = []
        for _ in range(random.randint(1, 3)):
            benchmark = self.create_new_benchmark_type()
            pressures.append(benchmark)
        return pressures


