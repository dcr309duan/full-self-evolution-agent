def mutate_fitness_landscape(test_dir: str = "tests") -> dict:
    """Main hook function that integrates all components."""
    result = {
        "timestamp": datetime.datetime.now().isoformat(),
        "test_dir": test_dir,
        "actions": []
    }
    
    # Step 1: Evolve test suite
    evolver = TestSuiteEvolver(test_dir)
    new_tests = evolver.evolve_test_suite()
    result["actions"].append({
        "component": "TestSuiteEvolver",
        "new_tests_generated": len(new_tests),
        "test_files": new_tests
    })
    
    # Step 2: Generate environmental pressure
    pressure_gen = EnvironmentalPressureGenerator()
    pressures = pressure_gen.generate_pressure()
    result["actions"].append({
        "component": "EnvironmentalPressureGenerator",
        "benchmarks_created": len(pressures),
        "benchmarks": pressures
    })
    
    # Step 3: Modify fitness landscape
    landscape_modifier = FitnessLandscapeModifier()
    modifications = landscape_modifier.modify_landscape()
    result["actions"].append({
        "component": "FitnessLandscapeModifier",
        "modifications_made": len(modifications),
        "modifications": modifications
    })
    
    return result


