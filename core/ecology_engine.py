def analyze_test_diversity(test_dir: str = "tests") -> dict:
    """Analyze diversity of test types in the test suite."""
    test_files = scan_test_suite(test_dir)
    diversity = {
        "unit": 0,
        "integration": 0,
        "stress": 0,
        "edge_case": 0,
        "other": 0
    }
    
    for filepath in test_files:
        basename = os.path.basename(filepath)
        if "stress" in basename.lower() or "load" in basename.lower() or "benchmark" in basename.lower() or "performance" in basename.lower():
            diversity["stress"] += 1
        elif "integration" in basename.lower() or "e2e" in basename.lower() or "end_to_end" in basename.lower() or "workflow" in basename.lower():
            diversity["integration"] += 1
        elif "edge" in basename.lower() or "corner" in basename.lower() or "boundary" in basename.lower() or "limit" in basename.lower() or "extreme" in basename.lower():
            diversity["edge_case"] += 1
        elif "unit" in basename.lower() or basename.startswith("test_"):
            diversity["unit"] += 1
        else:
            diversity["other"] += 1
    
    return diversity


