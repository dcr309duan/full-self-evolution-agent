def create_mutated_test(original_test_class, mutation_params=None):
    """Create a mutated version of a test class for ecological generation.
    
    Args:
        original_test_class: The test class to mutate
        mutation_params: Dictionary of mutation parameters (optional)
    
    Returns:
        A new test class with mutated behavior
    """
    if mutation_params is None:
        mutation_params = {}
    
    class MutatedTest(original_test_class):
        """Mutated test class generated by ecology engine."""
        
        @classmethod
        def setUpClass(cls):
            super().setUpClass()
            cls.metadata["test_type"] = "mutated"
            cls.metadata["generation_cycle"] += 1
            cls.metadata["mutation_params"] = mutation_params
    
    return MutatedTest


