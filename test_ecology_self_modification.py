        def mutate_existing_test(self, file_path):
            """Mutate an existing test file while preserving its basic structure.
            
            Args:
                file_path: Path to the existing test file to mutate.
                
            Returns:
                str: Path to the mutated test file.
            """
            import random
            import string
            
            # Read the existing test file
            with open(file_path, 'r') as f:
                content = f.read()
            
            # Extract the basic structure (function definitions, imports, docstrings)
            lines = content.split('\n')
            mutated_lines = []
            in_function = False
            function_indent = 0
            
            for line in lines:
                stripped = line.strip()
                
                # Preserve imports and docstrings
                if stripped.startswith('import ') or stripped.startswith('from ') or stripped.startswith('"""') or stripped.startswith("'''"):
                    mutated_lines.append(line)
                    continue
                
                # Preserve function definitions
                if stripped.startswith('def test_'):
                    in_function = True
                    function_indent = len(line) - len(line.lstrip())
                    mutated_lines.append(line)
                    continue
                
                # Inside a function, mutate assertions while preserving structure
                if in_function:
                    if stripped.startswith('assert '):
                        # Generate a new unique assertion
                        unique_val = random.randint(1, 1000)
                        mutated_lines.append(' ' * function_indent + f'assert {unique_val} == {unique_val}')
                    elif stripped == '' or stripped.startswith('#'):
                        mutated_lines.append(line)
                    elif stripped.startswith('"""') or stripped.startswith("'''"):
                        mutated_lines.append(line)
                    else:
                        # Keep other lines (like variable assignments) but may mutate values
                        if '=' in stripped and not stripped.startswith('assert'):
                            parts = stripped.split('=')
                            if len(parts) == 2:
                                var_name = parts[0].strip()
                                # Only mutate if it's a simple integer assignment
                                try:
                                    old_val = int(parts[1].strip())
                                    new_val = random.randint(1, 1000)
                                    mutated_lines.append(' ' * function_indent + f'{var_name} = {new_val}')
                                except ValueError:
                                    mutated_lines.append(line)
                            else:
                                mutated_lines.append(line)
                        else:
                            mutated_lines.append(line)
                else:
                    mutated_lines.append(line)
            
            # Write the mutated content to a new file
            mutated_content = '\n'.join(mutated_lines)
            mutated_filename = f"test_mutated_{''.join(random.choices(string.ascii_lowercase, k=8))}.py"
            mutated_path = os.path.join(self.temp_dir, mutated_filename)
            
            with open(mutated_path, 'w') as f:
                f.write(mutated_content)
            
            return mutated_path
        
