def test_environmental_pressure_creation(ecology_pressure_engine):
    """Test that environmental pressure creates a valid test file with unique assertions.
    
    This validates ecology loop step 1 by:
    1. Calling introduce_environmental_pressure()
    2. Verifying the returned file path exists
    3. Verifying the new test file contains at least one 'assert' statement
    4. Verifying the assertion is unique across all test files
    """
    # Step 1: Call introduce_environmental_pressure()
    file_path = ecology_pressure_engine.introduce_environmental_pressure()
    
    # Step 2: Verify the returned file path exists
    assert os.path.exists(file_path), f"Generated test file {file_path} does not exist"
    
    # Step 3: Verify the new test file contains at least one 'assert' statement
    with open(file_path, 'r') as f:
        content = f.read()
    assert 'assert' in content, f"Test file {file_path} does not contain any assert statement"
    
    # Step 4: Verify the assertion is unique by checking no other test file has the exact same assertion string
    # Extract all assert statements from the new file
    new_asserts = []
    for line in content.split('\n'):
        stripped = line.strip()
        if stripped.startswith('assert '):
            new_asserts.append(stripped)
    
    assert len(new_asserts) > 0, f"No assert statements found in {file_path}"
    
    # Check all test files in the tests directory for duplicate assertions
    test_dir = os.path.dirname(os.path.abspath(__file__))
    for root, dirs, files in os.walk(test_dir):
        for filename in files:
            if filename.endswith('.py') and filename != os.path.basename(file_path):
                other_file_path = os.path.join(root, filename)
                with open(other_file_path, 'r') as f:
                    other_content = f.read()
                for assert_stmt in new_asserts:
                    assert assert_stmt not in other_content, \
                        f"Assert statement '{assert_stmt}' from {file_path} already exists in {other_file_path}"


def test_self_modifying_test_suite(ecology_pressure_engine):
    """Test that the agent can modify its own fitness landscape by adding tests.
    
    This validates that:
    1. The initial set of test files is recorded
    2. Calling introduce_environmental_pressure() twice adds exactly 2 new files
    3. Both new files have unique assertions not present in the original suite
    """
    # Step 1: Record the initial set of test files
    test_dir = os.path.dirname(os.path.abspath(__file__))
    initial_files = set()
    for root, dirs, files in os.walk(test_dir):
        for filename in files:
            if filename.endswith('.py'):
                initial_files.add(os.path.join(root, filename))
    
    initial_count = len(initial_files)
    
    # Step 2: Call introduce_environmental_pressure() twice
    file_path_1 = ecology_pressure_engine.introduce_environmental_pressure()
    file_path_2 = ecology_pressure_engine.introduce_environmental_pressure()
    
    # Step 3: Verify the test suite grew by exactly 2 files
    current_files = set()
    for root, dirs, files in os.walk(test_dir):
        for filename in files:
            if filename.endswith('.py'):
                current_files.add(os.path.join(root, filename))
    
    new_files = current_files - initial_files
    assert len(new_files) == 2, f"Expected exactly 2 new files, but found {len(new_files)}: {new_files}"
    
    # Verify the returned paths are in the new files
    assert file_path_1 in new_files, f"First returned path {file_path_1} not in new files {new_files}"
    assert file_path_2 in new_files, f"Second returned path {file_path_2} not in new files {new_files}"
    
    # Step 4: Verify both new files have unique assertions
    for file_path in [file_path_1, file_path_2]:
        assert os.path.exists(file_path), f"New test file {file_path} does not exist"
        
        with open(file_path, 'r') as f:
            content = f.read()
        
        # Extract assert statements from the new file
        new_asserts = []
        for line in content.split('\n'):
            stripped = line.strip()
            if stripped.startswith('assert '):
                new_asserts.append(stripped)
        
        assert len(new_asserts) > 0, f"No assert statements found in {file_path}"
        
        # Check that these assertions are not in any initial file
        for initial_file in initial_files:
            with open(initial_file, 'r') as f:
                initial_content = f.read()
            for assert_stmt in new_asserts:
                assert assert_stmt not in initial_content, \
                    f"Assert statement '{assert_stmt}' from {file_path} already exists in initial file {initial_file}"
    
    # Also verify the two new files have different assertions from each other
    with open(file_path_1, 'r') as f:
        content_1 = f.read()
    with open(file_path_2, 'r') as f:
        content_2 = f.read()
    
    asserts_1 = set()
    for line in content_1.split('\n'):
        stripped = line.strip()
        if stripped.startswith('assert '):
            asserts_1.add(stripped)
    
    asserts_2 = set()
    for line in content_2.split('\n'):
        stripped = line.strip()
        if stripped.startswith('assert '):
            asserts_2.add(stripped)
    
    # Check that the two files don't share identical assert statements
    common_asserts = asserts_1.intersection(asserts_2)
    assert len(common_asserts) == 0, \
        f"New files share identical assert statements: {common_asserts}"


def test_generate_evolutionary_pressure(ecology_pressure_engine):
    """Test that generate_evolutionary_pressure() creates a unique and runnable benchmark.
    
    This validates that:
    1. The method returns a valid file path
    2. The generated benchmark file exists
    3. The benchmark file contains unique assertions not present in other test files
    4. The benchmark file is runnable (can be imported and executed)
    """
    # Step 1: Call generate_evolutionary_pressure()
    file_path = ecology_pressure_engine.generate_evolutionary_pressure()
    
    # Step 2: Verify the returned file path exists
    assert file_path is not None, "generate_evolutionary_pressure() returned None"
    assert os.path.exists(file_path), f"Generated benchmark file {file_path} does not exist"
    
    # Step 3: Verify the benchmark file contains unique assertions
    with open(file_path, 'r') as f:
        content = f.read()
    
    # Extract assert statements from the new benchmark
    new_asserts = []
    for line in content.split('\n'):
        stripped = line.strip()
        if stripped.startswith('assert '):
            new_asserts.append(stripped)
    
    assert len(new_asserts) > 0, f"No assert statements found in {file_path}"
    
    # Check that these assertions are unique across all test files
    test_dir = os.path.dirname(os.path.abspath(__file__))
    for root, dirs, files in os.walk(test_dir):
        for filename in files:
            if filename.endswith('.py') and filename != os.path.basename(file_path):
                other_file_path = os.path.join(root, filename)
                with open(other_file_path, 'r') as f:
                    other_content = f.read()
                for assert_stmt in new_asserts:
                    assert assert_stmt not in other_content, \
                        f"Assert statement '{assert_stmt}' from {file_path} already exists in {other_file_path}"
    
    # Step 4: Verify the benchmark file is runnable
    # Add the temp directory to sys.path temporarily
    temp_dir = os.path.dirname(file_path)
    original_sys_path = sys.path.copy()
    sys.path.insert(0, temp_dir)
    
    try:
        # Import the generated module
        module_name = os.path.basename(file_path).replace('.py', '')
        module = __import__(module_name)
        
        # Check that the module has test functions
        test_functions = [name for name in dir(module) if name.startswith('test_')]
        assert len(test_functions) > 0, f"No test functions found in {file_path}"
        
        # Run the test functions using pytest
        import subprocess
        result = subprocess.run(
            [sys.executable, '-m', 'pytest', file_path, '-v', '--tb=short'],
            capture_output=True,
            text=True,
            timeout=30
        )
        
        # Verify the tests passed
        assert result.returncode == 0, f"Benchmark tests failed:\n{result.stdout}\n{result.stderr}"
        assert "passed" in result.stdout.lower(), f"No passed tests found in output:\n{result.stdout}"
        
    finally:
        # Restore sys.path
        sys.path = original_sys_path


