        # Step 2: Verify each new test has unique assertions not found in existing tests
        all_existing_assertions = set(initial_assertions)
        for file_path in generated_files:
            with open(file_path, 'r') as f:
                content = f.read()
            
            # Extract assertions from the new file
            new_asserts = []
            for line in content.split('\n'):
                stripped = line.strip()
                if stripped.startswith('assert '):
                    new_asserts.append(stripped)
            
            self.assertGreater(len(new_asserts), 0, f"No assert statements found in {file_path}")
            
            # Verify each assertion is unique
            for assert_stmt in new_asserts:
                self.assertNotIn(assert_stmt, all_existing_assertions,
                    f"Assert statement '{assert_stmt}' from {file_path} already exists in existing tests")
                all_existing_assertions.add(assert_stmt)
        
        # Step 3: Mutate an existing test without breaking its basic structure
        # Use one of the generated files as the source for mutation
        source_file = generated_files[0]
        mutated_path = engine.mutate_existing_test(source_file)
        
        self.assertIsNotNone(mutated_path, "Mutation returned None")
        self.assertTrue(os.path.exists(mutated_path), f"Mutated file {mutated_path} does not exist")
        
        # Verify the mutated file preserves basic structure
        with open(source_file, 'r') as f:
            source_content = f.read()
        with open(mutated_path, 'r') as f:
            mutated_content = f.read()
        
        # Check that function definitions are preserved
        source_functions = [line for line in source_content.split('\n') if line.strip().startswith('def test_')]
        mutated_functions = [line for line in mutated_content.split('\n') if line.strip().startswith('def test_')]
        self.assertEqual(len(source_functions), len(mutated_functions),
            "Mutation changed the number of test functions")
        
        # Check that imports are preserved
        source_imports = [line for line in source_content.split('\n') if line.strip().startswith('import ') or line.strip().startswith('from ')]
        mutated_imports = [line for line in mutated_content.split('\n') if line.strip().startswith('import ') or line.strip().startswith('from ')]
        self.assertEqual(len(source_imports), len(mutated_imports),
            "Mutation changed the number of import statements")
        
        # Verify the mutated file has valid Python syntax
        try:
            compile(mutated_content, mutated_path, 'exec')
        except SyntaxError as e:
            self.fail(f"Mutated file {mutated_path} contains invalid Python syntax: {e}")
        
        # Step 4: Verify new tests are properly registered and discoverable
        # Check that all generated files are in the engine's temp directory
        for file_path in generated_files + [mutated_path]:
            self.assertTrue(os.path.exists(file_path), f"File {file_path} is not discoverable")
            self.assertIn(os.path.dirname(file_path), [engine.temp_dir],
                f"File {file_path} is not registered in the engine's temp directory")
        
        # Verify the files can be imported as modules
        original_sys_path = sys.path.copy()
        sys.path.insert(0, engine.temp_dir)
        try:
            for file_path in generated_files + [mutated_path]:
                module_name = os.path.basename(file_path).replace('.py', '')
                try:
                    module = __import__(module_name)
                    # Verify the module has test functions
                    test_functions = [name for name in dir(module) if name.startswith('test_')]
                    self.assertGreater(len(test_functions), 0,
                        f"Module {module_name} has no test functions")
                except ImportError as e:
                    self.fail(f"Cannot import module {module_name}: {e}")
        finally:
            sys.path = original_sys_path
        
        # Step 5: Verify the test suite grows by at least 20%
        final_count = engine.get_test_count()
        growth_threshold = initial_count * 0.2  # 20% growth
        
        # Count new files (excluding the initial ones)
        new_files_count = final_count - initial_count
        self.assertGreaterEqual(new_files_count, growth_threshold,
            f"Test suite growth ({new_files_count} new files) is less than 20% of initial count ({initial_count})")
        
        # Also verify that the total number of assertions has increased
        final_assertions = engine.get_all_assertions()
        assertion_growth = len(final_assertions) - len(initial_assertions)
        self.assertGreater(assertion_growth, 0,
            f"No new assertions were added to the test suite")


